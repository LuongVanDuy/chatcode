const fs = require('fs');
const file = 'core/machine-access.js';
let text = fs.readFileSync(file, 'utf8');
const anchor = "    const original = {};\n    for (const name of ['listProjects','listFiles','search','readFile','readFiles','writeFile','deleteFile','renameFile','runTask','exec','applyAndVerify','inspectProject','prepareTask','projectScope']) {\n      if (typeof api[name] === 'function') original[name] = api[name].bind(api);\n    }\n";
if (!text.includes(anchor)) throw new Error('machine API anchor missing');
text = text.replace(anchor, anchor + "    const resolveStoredProject = ref => { try { return store.getProject(ref); } catch { return null; } };\n");
const marker = 'const project = store.getProject(ref);';
const count = text.split(marker).length - 1;
if (count < 8) throw new Error(`Expected persisted-project lookups, got ${count}`);
text = text.split(marker).join('const project = resolveStoredProject(ref);');
fs.writeFileSync(file, text, 'utf8');
console.log(`Legacy compatibility patched across ${count} machine wrappers.`);
